import React, { useRef, useState } from 'react';
import { membersAPI, reportsAPI } from '../api';
import './reports.css';

const kes = n => 'KES ' + new Intl.NumberFormat('en-KE', { minimumFractionDigits: 2, maximumFractionDigits: 2 }).format(n || 0);
const firstOfMonth = () => { const d = new Date(); return new Date(d.getFullYear(), d.getMonth(), 1).toISOString().slice(0, 10); };
const today = () => new Date().toISOString().slice(0, 10);
const label = t => (t || '').replace(/_/g, ' ');

function GivingReport() {
  const [from, setFrom] = useState(firstOfMonth());
  const [to, setTo] = useState(today());
  const [data, setData] = useState(null);
  const [error, setError] = useState('');
  const run = async () => {
    setError('');
    try { setData((await reportsAPI.giving({ from, to })).data); }
    catch (err) { setData(null); setError(err.response?.data?.error || 'Could not build the report.'); }
  };
  return (
    <section>
      <div className="rp-controls no-print">
        <label>From <input type="date" className="form-control" value={from} onChange={e => setFrom(e.target.value)} /></label>
        <label>To <input type="date" className="form-control" value={to} onChange={e => setTo(e.target.value)} /></label>
        <button type="button" className="cd-act" onClick={run}>Build report</button>
        {data && <button type="button" className="cd-act alt" onClick={() => window.print()}>Save as PDF</button>}
      </div>
      {error && <div className="cd-err no-print" role="alert"><span>{error}</span></div>}
      {data && (
        <div className="rp-sheet">
          <h2 className="rp-title">{data.church || 'Church'} · Giving and spending</h2>
          <p className="rp-sub">{data.from} to {data.to} · {data.count} entries · voided entries excluded</p>
          <div className="rp-totals">
            <div><span>Income</span><b>{kes(data.income_total)}</b></div>
            <div><span>Spending</span><b>{kes(data.expense_total)}</b></div>
            <div><span>Net</span><b>{kes(data.net)}</b></div>
          </div>
          <h3>By type</h3>
          <table className="rp-table"><thead><tr><th>Type</th><th>Entries</th><th>Total</th></tr></thead>
            <tbody>{data.by_type.map(r => <tr key={r.type}><td>{label(r.type)}</td><td>{r.count}</td><td>{kes(r.total)}</td></tr>)}</tbody></table>
          <h3>Income by category</h3>
          <table className="rp-table"><thead><tr><th>Category</th><th>Total</th></tr></thead>
            <tbody>{data.by_category.map(r => <tr key={r.category}><td>{r.category}</td><td>{kes(r.total)}</td></tr>)}</tbody></table>
          <h3>By month</h3>
          <table className="rp-table"><thead><tr><th>Month</th><th>Income</th><th>Spending</th></tr></thead>
            <tbody>{data.by_month.map(r => <tr key={r.month}><td>{r.month}</td><td>{kes(r.income)}</td><td>{kes(r.expense)}</td></tr>)}</tbody></table>
          <p className="rp-foot">Generated by ChurchOS on {data.generated_at.replace('T', ' ').replace('Z', ' UTC')}. Figures come only from recorded, unvoided entries.</p>
        </div>
      )}
    </section>
  );
}

function MemberStatement() {
  const [text, setText] = useState('');
  const [found, setFound] = useState([]);
  const [member, setMember] = useState(null);
  const [year, setYear] = useState(new Date().getFullYear());
  const [data, setData] = useState(null);
  const [error, setError] = useState('');
  const timer = useRef(null);
  const search = q => {
    setText(q);
    clearTimeout(timer.current);
    if (q.trim().length < 2) { setFound([]); return; }
    timer.current = setTimeout(() => {
      membersAPI.getAll({ search: q.trim(), per_page: 8 }).then(r => setFound(r.data.members || [])).catch(() => setFound([]));
    }, 300);
  };
  const run = async () => {
    if (!member) return;
    setError('');
    try { setData((await reportsAPI.member(member.id, { year })).data); }
    catch (err) { setData(null); setError(err.response?.data?.error || 'Could not build the statement.'); }
  };
  const years = [];
  for (let y = new Date().getFullYear(); y >= new Date().getFullYear() - 5; y -= 1) years.push(y);
  return (
    <section>
      <div className="rp-controls no-print">
        {member ? (
          <span className="cd-item"><b>{member.full_name}</b>&nbsp;{member.member_id}
            <button type="button" className="cd-call" onClick={() => { setMember(null); setData(null); }}>Change</button></span>
        ) : (
          <input className="form-control" placeholder="Find a member" value={text} onChange={e => search(e.target.value)} aria-label="Find a member" />
        )}
        <select className="form-control" value={year} onChange={e => setYear(Number(e.target.value))} aria-label="Year">
          {years.map(y => <option key={y} value={y}>{y}</option>)}
        </select>
        <button type="button" className="cd-act" onClick={run} disabled={!member}>Build statement</button>
        {data && <button type="button" className="cd-act alt" onClick={() => window.print()}>Save as PDF</button>}
      </div>
      {!member && found.length > 0 && (
        <ul className="cd-list no-print">{found.map(m => (
          <li key={m.id}><button type="button" className="cd-item" style={{ width: '100%', border: 0, cursor: 'pointer' }}
            onClick={() => { setMember(m); setFound([]); setText(''); }}><b>{m.full_name}</b><span>{m.member_id}</span></button></li>
        ))}</ul>
      )}
      {error && <div className="cd-err no-print" role="alert"><span>{error}</span></div>}
      {data && (
        <div className="rp-sheet">
          <h2 className="rp-title">{data.church || 'Church'} · Giving statement {data.year}</h2>
          <p className="rp-sub">{data.member.full_name} · {data.member.member_id}</p>
          {data.items.length === 0 ? <p>No giving recorded for this year.</p> : (
            <table className="rp-table"><thead><tr><th>Date</th><th>Type</th><th>Reference</th><th>Amount</th></tr></thead>
              <tbody>{data.items.map(i => <tr key={i.reference}><td>{i.date}</td><td>{label(i.type)}</td><td>{i.mpesa_ref || i.reference}</td><td>{kes(i.amount)}</td></tr>)}</tbody></table>
          )}
          <div className="rp-totals"><div><span>Total for {data.year}</span><b>{kes(data.total)}</b></div></div>
          <p className="rp-foot">Generated by ChurchOS on {data.generated_at.replace('T', ' ').replace('Z', ' UTC')}. Thank you for your faithful giving.</p>
        </div>
      )}
    </section>
  );
}

export default function Reports() {
  const [tab, setTab] = useState('giving');
  return (
    <div className="cd">
      <div className="cd-head no-print">
        <div>
          <h1 className="cd-title">Reports</h1>
          <p className="cd-sub">Build a report, then tap Save as PDF and choose "Save as PDF" as the printer.</p>
        </div>
      </div>
      <div className="cd-actions no-print" style={{ marginBottom: '1rem' }}>
        <button type="button" className={`cd-act ${tab === 'giving' ? '' : 'alt'}`} onClick={() => setTab('giving')}>Giving report</button>
        <button type="button" className={`cd-act ${tab === 'member' ? '' : 'alt'}`} onClick={() => setTab('member')}>Member statement</button>
      </div>
      {tab === 'giving' ? <GivingReport /> : <MemberStatement />}
    </div>
  );
}
